import {test,expect} from '@playwright/test';
import {createHash} from 'node:crypto';

test('parse repair is independently reviewed; publication refreshes retrieval and FAQ; rollback stays explicit',async({page,request})=>{
  test.setTimeout(180000);
  page.setDefaultTimeout(15000);
  const pageErrors:string[]=[];page.on("pageerror",error=>pageErrors.push(error.message));
  const password=process.env.WORKBENCH_TEST_PASSWORD, api=process.env.WORKBENCH_TEST_URL;
  if(!password||!api)throw new Error('Isolated fixture required');
  const title='解析修订闭环演示-'+Date.now();
  const original=Buffer.from(`PARSE-LOSS-DEMO ${title}\n\n# 退货政策\n\n普通商品签收七天内可申请退货。定制商品除外。`);
  const auth=await request.post(api+'/api/v1/auth/login',{data:{organization:'demo-a',email:'admin@demo.test',password}});
  const headers={Authorization:'Bearer '+(await auth.json()).access_token};
  const upload=await request.post(api+'/api/v1/knowledge/documents',{headers,multipart:{title,policy_scope:'returns',chunk_strategy:'parent_child',file:{name:'parse-demo.md',mimeType:'text/markdown',buffer:original}}});
  expect(upload.ok()).toBeTruthy();const base=await upload.json(),version=base.version.id;expect(base.created).toBeTruthy();
  async function ready(id:string){await expect.poll(async()=> (await (await request.get(api+'/api/v1/knowledge/versions/'+id,{headers})).json()).status,{timeout:60000}).toBe('ready');}
  await ready(version);expect((await request.post(api+'/api/v1/knowledge/versions/'+version+'/publish',{headers,data:{}})).ok()).toBeTruthy();
  const blocks=await (await request.get(api+'/api/v1/knowledge/versions/'+version+'/parse',{headers})).json();
  const block=blocks.blocks.find((b:any)=>b.text.includes('七天'));expect(block.text).not.toContain('定制商品除外');
  const faqText=Buffer.from('问：退货期限？答：普通商品签收七天内，定制商品除外。');
  const faqUpload=await request.post(api+'/api/v1/knowledge/documents',{headers,multipart:{title:'依赖FAQ-'+title,knowledge_kind:'faq',faq_sources:JSON.stringify([version]),policy_scope:'returns',file:{name:'faq.md',mimeType:'text/markdown',buffer:faqText}}});
  const faq=await faqUpload.json();expect(faqUpload.ok()).toBeTruthy();await ready(faq.version.id);
  expect((await request.post(api+'/api/v1/knowledge/versions/'+faq.version.id+'/publish',{headers,data:{}})).ok()).toBeTruthy();
  async function login(email:string){await page.goto('/');if(await page.getByRole('button',{name:'退出登录'}).count())await page.getByRole('button',{name:'退出登录'}).click();await page.getByLabel('邮箱').fill(email);await page.getByLabel('密码').fill(password);await page.getByRole('button',{name:'进入工作台'}).click();await page.getByRole('button',{name:'知识库',exact:true}).click();}
  await login('admin@demo.test');
  let card=page.locator('article.document-card').filter({has:page.getByRole('heading',{name:title,exact:true})});
  await card.getByRole('button',{name:'核对解析 v1',exact:true}).click();
  let panel=page.getByRole('article',{name:'解析修订面板'});
  await panel.getByLabel('解析段落 '+(block.index+1),{exact:true}).fill(block.text+'定制商品除外。');
  await panel.getByLabel('修订处理原因').fill('对照原文件补回解析遗漏的定制商品例外');
  await panel.getByRole('button',{name:'提交解析修订新版本'}).click();
  await expect(panel.getByRole('status')).toContainText('操作已记录');
  const docs=await (await request.get(api+'/api/v1/knowledge/documents',{headers})).json();
  const edited=docs.items.find((d:any)=>d.id===base.document_id).versions.find((v:any)=>v.number===2);
  await ready(edited.id);
  expect((await request.post(api+'/api/v1/knowledge/versions/'+edited.id+'/publish',{headers,data:{}})).status()).toBe(409);
  await login('approver@demo.test');
  card=page.locator('article.document-card').filter({has:page.getByRole('heading',{name:title,exact:true})});
  await card.getByRole('button',{name:'核对解析 v2',exact:true}).click();
  panel=page.getByRole('article',{name:'解析修订面板'});
  await expect(panel).toContainText('修订前');await expect(panel).toContainText('修订后');
  await panel.getByLabel('修订处理原因').fill('已逐字核对原文件和修订后的例外条款');
  await panel.getByRole('button',{name:'批准解析修订'}).click();
  await expect(panel).toContainText('审核通过');
  await login('admin@demo.test');
  card=page.locator('article.document-card').filter({has:page.getByRole('heading',{name:title,exact:true})});
  await card.getByRole('button',{name:'发布 v2',exact:true}).click();
  await expect.poll(async()=> (await (await request.get(api+'/api/v1/knowledge/versions/'+edited.id,{headers})).json()).published).toBeTruthy();
  const found=await (await request.post(api+'/api/v1/knowledge/search',{headers,data:{query:'定制商品退货',version_id:edited.id,strategy:'hybrid_rerank',top_k:3}})).json();
  expect(found.matches.length).toBeGreaterThan(0);expect(found.matches.every((m:any)=>m.version_id===edited.id&&m.text_origin==='human_corrected_parse')).toBeTruthy();
  expect(found.matches.some((m:any)=>m.content.includes('定制商品除外'))).toBeTruthy();
  expect((await (await request.get(api+'/api/v1/knowledge/versions/'+faq.version.id,{headers})).json()).source_review_required).toBeTruthy();
  const staleFaq=await (await request.post(api+'/api/v1/knowledge/search',{headers,data:{query:'退货期限',version_id:faq.version.id,strategy:'hybrid_rerank'}})).json();expect(staleFaq.matches).toEqual([]);
  const refreshed=await request.post(api+'/api/v1/knowledge/documents/'+faq.document_id+'/versions',{headers,multipart:{knowledge_kind:'faq',faq_sources:JSON.stringify([edited.id]),file:{name:'faq.md',mimeType:'text/markdown',buffer:faqText}}});
  expect(refreshed.ok()).toBeTruthy();const newFaq=(await refreshed.json()).version.id;await ready(newFaq);
  expect((await request.post(api+'/api/v1/knowledge/versions/'+newFaq+'/publish',{headers,data:{}})).ok()).toBeTruthy();
  expect((await (await request.get(api+'/api/v1/knowledge/versions/'+newFaq,{headers})).json()).source_review_required).toBeFalsy();
  const currentFaq=await (await request.post(api+'/api/v1/knowledge/search',{headers,data:{query:'退货期限',version_id:newFaq,strategy:'hybrid_rerank'}})).json();expect(currentFaq.matches.length).toBeGreaterThan(0);
  const downloaded=await (await request.get(api+'/api/v1/knowledge/versions/'+edited.id+'/file',{headers})).body();
  expect(createHash('sha256').update(downloaded).digest('hex')).toBe(createHash('sha256').update(original).digest('hex'));
  await card.getByRole('button',{name:'核对解析 v1',exact:true}).click();
  panel=page.getByRole('article',{name:'解析修订面板'});
  await panel.getByLabel('修订处理原因').fill('演示显式回退并保留FAQ待复核要求');
  await panel.getByRole('button',{name:'回退到此已发布版本'}).click();
  await expect(panel.getByRole('status')).toContainText('操作已记录');
  expect((await (await request.get(api+'/api/v1/knowledge/versions/'+newFaq,{headers})).json()).source_review_required).toBeTruthy();
  const rolledFaq=await (await request.post(api+'/api/v1/knowledge/search',{headers,data:{query:'退货期限',version_id:newFaq,strategy:'hybrid_rerank'}})).json();expect(rolledFaq.matches).toEqual([]);
  expect(pageErrors).toEqual([]);
  await page.screenshot({path:'../work/knowledge-revision-v1/reviewed-revision.png',fullPage:true});
});
