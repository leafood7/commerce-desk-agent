import {test,expect} from '@playwright/test';

test('return Agent reads original clauses then asks the missing item fact and reaches preview',async({page,request})=>{
  test.setTimeout(180000);
  const password=process.env.WORKBENCH_TEST_PASSWORD;
  const api=process.env.WORKBENCH_TEST_URL;
  const order=process.env.SOURCE_AGENT_ORDER;
  if(!password||!api||!order)throw new Error('Isolated fixture required');
  await page.goto('/');
  await page.getByLabel('邮箱').fill('admin@demo.test');await page.getByLabel('密码').fill(password);
  await page.getByRole('button',{name:'进入工作台'}).click();
  await page.getByRole('button',{name:'配置版本',exact:true}).click();
  await page.getByLabel('模型选择').selectOption('rules');
  await page.getByLabel('政策回答方式').selectOption('excerpts');
  await page.getByLabel('退货动作决策').selectOption('rules');
  await page.getByLabel('检索候选数').selectOption('1');
  await page.getByLabel('退货流程').selectOption('guided_v3');
  await page.getByLabel('退货政策范围').selectOption('clause_bound');
  await page.getByLabel('按需阅读原文').selectOption('true');
  await page.getByRole('button',{name:'保存配置草稿'}).click();
  await expect(page.getByRole('status')).toContainText('已保存草稿');
  await page.getByRole('button',{name:'发布选中版本'}).click();
  await expect(page.getByRole('status')).toContainText('已发布');
  await page.getByRole('button',{name:'退出登录'}).click();
  await page.getByLabel('邮箱').fill('support@demo.test');await page.getByLabel('密码').fill(password);
  await page.getByRole('button',{name:'进入工作台'}).click();
  await page.getByRole('button',{name:'退货申请',exact:true}).click();
  await page.getByLabel('退货订单号').fill(order);
  await page.getByRole('button',{name:'读取退货订单'}).click();
  await page.getByLabel('退货规则').selectOption(process.env.SOURCE_AGENT_POLICY!);
  await page.getByLabel('退货原因').fill('演示按需阅读退货');
  await page.getByLabel('商品状态',{exact:true}).selectOption('unknown');
  await page.getByLabel('退货核对需求').fill('请核对当前演示商品的退货申请条件。');
  const pending=page.waitForResponse(r=>r.url().endsWith('/api/v1/runs')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'启动退货 Agent 核对'}).click();
  const id=(await (await pending).json()).id;
  await expect(page.getByText('流程状态：awaiting_input')).toBeVisible({timeout:90000});
  await page.getByText('原文补查记录',{exact:true}).click();
  await expect(page.getByText(/补读 1\/2 次/)).toBeVisible();
  await page.getByLabel('商品状态',{exact:true}).selectOption('unused');
  await page.getByRole('button',{name:'补充退货条件'}).click();
  await expect(page.getByRole('button',{name:'确认已核对的退货预览'})).toBeVisible({timeout:60000});
  await expect(page.getByText(/补读 2\/2 次/)).toBeVisible();
  const login=await request.post(api+'/api/v1/auth/login',{data:{organization:'demo-a',email:'support@demo.test',password}});
  const headers={Authorization:'Bearer '+(await login.json()).access_token};
  const run=await (await request.get(api+'/api/v1/runs/'+id,{headers})).json();
  expect(run.status).toBe('awaiting_confirmation');expect(run.output.request).toBeFalsy();
  expect(run.output.source_investigation.reads).toBe(2);
  const usage=await (await request.get(api+'/api/v1/runs/'+id+'/usage',{headers})).json();
  expect(usage.model_attempts).toBe(0);
  await page.screenshot({path:'../work/source-agent-v1/return-source-preview.png',fullPage:true});
});
