import {test,expect} from '@playwright/test';

test('stage1 upload, publish, clarify, read linked original and invalidate FAQ on source update',async({page,request})=>{
  test.setTimeout(180000);
  const password=process.env.WORKBENCH_TEST_PASSWORD;
  if(!password)throw new Error('Private isolated password required');
  const api=process.env.WORKBENCH_TEST_URL||'http://127.0.0.1:18182';
  const title='阶段1浏览器政策-'+Date.now();
  const audience={merchant:'阶段1演示',region:'大陆',channel:'线上'};
  const text='# 第1条 退货期限\n\n普通商品七天内可申请退货，例外参见第3条。\n\n# 第2条 流程\n\n请先核对商品与数量。\n\n# 第3条 商品例外\n\n定制商品不适用上述无理由退货规则。\n\n# 验收批次\n\n'+title;
  await page.goto('/');
  await page.getByLabel('邮箱').fill('admin@demo.test');
  await page.getByLabel('密码').fill(password);
  await page.getByRole('button',{name:'进入工作台'}).click();
  await page.getByRole('button',{name:'知识库',exact:true}).click();
  await page.getByLabel('文档名称').fill(title);
  await page.getByLabel('适用范围',{exact:true}).selectOption('returns');
  await page.getByLabel('分块方式').selectOption('parent_child');
  await page.getByLabel('适用商家').fill(audience.merchant);
  await page.getByLabel('适用地区').fill(audience.region);
  await page.getByLabel('适用渠道').fill(audience.channel);
  await page.getByLabel('政策文件').setInputFiles({name:'policy.md',mimeType:'text/markdown',buffer:Buffer.from(text)});
  await page.getByRole('button',{name:'上传并处理'}).click();
  const card=page.locator('.document-card').filter({has:page.getByRole('heading',{name:title,exact:true})});
  await expect(card.getByRole('button',{name:'发布 v1'})).toBeVisible({timeout:60000});
  await card.getByRole('button',{name:'发布 v1'}).click();
  await expect(card.getByText('当前已发布',{exact:false})).toBeVisible();
  await page.getByRole('button',{name:'政策检索',exact:true}).click();
  await page.getByLabel('政策问题').fill('普通商品七天内申请退货的期限和例外是什么？');
  await page.getByLabel('商家',{exact:true}).fill(audience.merchant);
  await page.getByRole('button',{name:'检索政策',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('请先明确',{timeout:60000});
  await expect(page.locator('.evidence')).toHaveCount(0);
  await page.getByLabel('地区',{exact:true}).fill(audience.region);
  await page.getByLabel('购买渠道',{exact:true}).fill(audience.channel);
  await page.getByRole('button',{name:'检索政策',exact:true}).click();
  await expect(page.locator('.evidence').first()).toBeVisible({timeout:60000});
  await page.getByRole('button',{name:'阅读相关原文章节'}).first().click();
  await expect(page.getByText('本章节已读完；其他章节的例外仍需核对。',{exact:true}).first()).toBeVisible();
  await page.screenshot({path:'../work/rag-upgrade-v1/source-reading.png',fullPage:true});
  // Changing the explicit scope clears old evidence before another request.
  await page.getByLabel('购买渠道',{exact:true}).fill('门店');
  await expect(page.locator('.evidence')).toHaveCount(0);
  await page.getByRole('button',{name:'检索政策',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('没有可用依据',{timeout:60000});
  const auth=await request.post(api+'/api/v1/auth/login',{data:{organization:'demo-a',email:'admin@demo.test',password}});
  expect(auth.ok()).toBeTruthy();
  const headers={Authorization:'Bearer '+(await auth.json()).access_token};
  const documents=await (await request.get(api+'/api/v1/knowledge/documents',{headers})).json();
  const source=documents.items.find((d:any)=>d.title===title);
  expect(source).toBeTruthy();const sourceId=source.active_version_id;
  const linked=await request.post(api+'/api/v1/knowledge/read',{headers,data:{version_id:sourceId,parent_id:'p0',audience}});
  expect(linked.ok()).toBeTruthy();expect((await linked.json()).related_sections).toContainEqual({parent_id:'p2',section:'第3条 商品例外'});
  const faq=await request.post(api+'/api/v1/knowledge/documents',{headers,multipart:{title:'FAQ-'+title,chunk_strategy:'parent_child',knowledge_kind:'faq',audience:JSON.stringify(audience),faq_sources:JSON.stringify([sourceId]),file:{name:'faq.md',mimeType:'text/markdown',buffer:Buffer.from('# 常见问题\n\n普通商品七天内可申请，定制商品除外。')}}});
  expect(faq.ok()).toBeTruthy();const faqId=(await faq.json()).version.id;
  await expect.poll(async()=> (await (await request.get(api+'/api/v1/knowledge/versions/'+faqId,{headers})).json()).status,{timeout:60000}).toBe('ready');
  expect((await request.post(api+'/api/v1/knowledge/versions/'+faqId+'/publish',{headers,data:{}})).ok()).toBeTruthy();
  const changed=await request.post(api+'/api/v1/knowledge/documents/'+source.id+'/versions',{headers,multipart:{chunk_strategy:'parent_child',file:{name:'v2.md',mimeType:'text/markdown',buffer:Buffer.from(text+'\n\n本版本新增人工审核说明。')}}});
  expect(changed.ok()).toBeTruthy();const newId=(await changed.json()).version.id;
  await expect.poll(async()=> (await (await request.get(api+'/api/v1/knowledge/versions/'+newId,{headers})).json()).status,{timeout:60000}).toBe('ready');
  expect((await request.post(api+'/api/v1/knowledge/versions/'+newId+'/publish',{headers,data:{}})).ok()).toBeTruthy();
  const stale=await request.get(api+'/api/v1/knowledge/versions/'+faqId,{headers});
  expect((await stale.json()).source_review_required).toBe(true);
  expect((await request.post(api+'/api/v1/knowledge/read',{headers,data:{version_id:faqId,parent_id:'p0'}})).status()).toBe(409);
  await page.getByRole('button',{name:'知识库',exact:true}).click();
  await expect(page.getByText('关联政策已变更或失效，FAQ暂停检索，请审核并发布新版本。',{exact:true}).first()).toBeVisible();
});
