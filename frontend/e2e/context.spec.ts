import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';

test('completed read exposes only current context and survives page reload after reauthentication',async({page,request})=>{
  test.setTimeout(120000);
  const password=process.env.WORKBENCH_TEST_PASSWORD;
  if(!password)throw new Error('Set private local acceptance password');
  const api=process.env.WORKBENCH_TEST_URL||'http://127.0.0.1:18082';
  const fixture=JSON.parse(readFileSync(new URL('../../work/returns-v1/demo.json',import.meta.url),'utf-8'));
  const order=fixture.orders.normal.number;
  const auth=await request.post(api+'/api/v1/auth/login',{data:{organization:'demo-a',email:'support@demo.test',password}});
  expect(auth.ok()).toBeTruthy();
  const headers={Authorization:'Bearer '+(await auth.json()).access_token};
  const created=await request.post(api+'/api/v1/runs',{headers:{...headers,'Idempotency-Key':crypto.randomUUID()},data:{kind:'aftersales',query:'查询订单实际签收时间，只查询',order_number:order}});
  expect(created.ok()).toBeTruthy();
  const id=(await created.json()).id;
  await expect.poll(async()=> (await (await request.get(api+'/api/v1/runs/'+id,{headers})).json()).status,{timeout:60000}).toBe('completed');
  const context=await (await request.get(api+'/api/v1/runs/'+id+'/context',{headers})).json();
  expect(context.context.active_order).toBe(order);
  expect(context.context.history_is_evidence).toBe(false);
  expect(context.context.summary).toBeUndefined();
  const events=await request.get(api+'/api/v1/runs/'+id+'/events',{headers});
  expect((await events.text())).toContain('answer.published');
  await page.goto('/');
  await page.getByLabel('邮箱').fill('support@demo.test');
  await page.getByLabel('密码').fill(password);
  await page.getByRole('button',{name:'进入工作台'}).click();
  await page.getByRole('button',{name:'售后助手',exact:true}).click();
  await page.getByLabel('恢复已有流程').selectOption(id);
  await page.getByText('最近核对的信息',{exact:false}).click();
  await expect(page.getByText('历史摘要不作为政策依据或审批凭据。',{exact:false})).toBeVisible();
  await page.reload();
  await page.getByLabel('邮箱').fill('support@demo.test');
  await page.getByLabel('密码').fill(password);
  await page.getByRole('button',{name:'进入工作台'}).click();
  await page.getByRole('button',{name:'售后助手',exact:true}).click();
  await page.getByLabel('恢复已有流程').selectOption(id);
  await expect(page.getByText('最近核对的信息',{exact:false})).toBeVisible();
});
